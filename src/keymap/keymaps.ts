/** A keymap's command → keys, as written in the specs above (ids written short: "find", "commentLine"). */
export type Bindings = Map<string, string[]>;

/** A spec's short id ("find", "commentLine", "tool.git") → the catalog's. */
export function resolveId(id: string): string | null {
  for (const full of [id, `phpblitz.${id}`, `editor.action.${id}`]) if (command(full)) return full;
  return null;
}

function fromSpec(spec: Spec): Bindings {
  const out: Bindings = new Map();
  for (const [short, keys] of Object.entries(spec)) {
    const id = resolveId(short);
    if (!id) {
      console.warn(`Keymap: unknown command ${short}`);
      continue;
    }
    out.set(id, (Array.isArray(keys) ? keys : [keys]).map((k) => normalizeKeys(k) ?? k));
  }
  return out;
}

/** Two key strings that can't both work: the same, or one starts the other's chord. */
export function clash(a: string, b: string): boolean {
  if (a === b) return true;
  const [a1, a2] = a.split(' ');
  const [b1, b2] = b.split(' ');
  // Gestures ("Double Ctrl Up") are made of words, not strokes.
  if (a.startsWith('Double ') || b.startsWith('Double ')) return false;
  return (!!a2 !== !!b2 && a1 === b1);
}

/**
 * Cmd keys macOS keeps for itself (Quit, Hide, Minimize, Spotlight, app and window switching): the
 * app never sees them. There, keymaps' "Ctrl" (Cmd) versions of these use the real Control key,
 * as editors on macOS do (Control+Space for completion, Control+Tab between files).
 */
const MAC_RESERVED = new Set(['Ctrl+Q', 'Ctrl+H', 'Ctrl+Alt+H', 'Ctrl+M', 'Ctrl+Space', 'Ctrl+Tab', 'Ctrl+Shift+Tab', 'Ctrl+`', 'Ctrl+Alt+Escape']);

/** On macOS, keys whose first stroke the system keeps move from Cmd to Control. */
export function macKeys(keys: string): string {
  const [first, ...rest] = keys.split(' ');
  if (keys.startsWith('Double ') || !MAC_RESERVED.has(first)) return keys;
  return [first.replace(/^Ctrl\+/, 'Meta+'), ...rest].join(' ');
}

const cache = new Map<KeymapId, Bindings>();

/** Every catalog command's keys in this keymap, PHPBlitz's filling the gaps where they're free. */
export function presetBindings(id: KeymapId): Bindings {
  const hit = cache.get(id);
  if (hit) return hit;
  const own = fromSpec((KEYMAPS.find((k) => k.id === id) ?? KEYMAPS[0]).spec);
  const result: Bindings = new Map(own);
  if (id !== 'phpblitz') {
    const used = [...own.values()].flat();
    const base = presetBindings('phpblitz');
    for (const c of COMMANDS) {
      if (own.has(c.id)) continue;
      const keys = (base.get(c.id) ?? []).filter((k) => !used.some((u) => clash(u, k)));
      if (keys.length) result.set(c.id, keys);
    }
  }
  if (isMac) for (const [command, keys] of result) result.set(command, keys.map(macKeys));
  cache.set(id, result);
  return result;
}
